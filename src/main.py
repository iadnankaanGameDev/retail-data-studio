
from pathlib import Path
import subprocess
import sys
import json
from datetime import datetime
from uuid import uuid4
import csv
import argparse
import os
from runtime import worker_command
from paths import (
    BASE_DIR,
    SRC_DIR,
    PROCESSED_DIR,
    QUARANTINE_DIR,
    resolve_project_path
)



def export_processing_history(output_dir):
    summary_dir = output_dir / "run_summaries"
    output_path = output_dir / "processing_history.csv"

    columns = [
        "run_id",
        "source_file",
        "started_at",
        "completed_at",
        "status",
        "failed_step",
        "total_records",
        "validation_accepted",
        "validation_rejected",
        "new_records",
        "already_present",
        "total_database_records",
        "error"
    ]

    records = []

    # Read all saved run summaries
    for path in sorted(summary_dir.glob("*.json")):
        with path.open("r", encoding="utf-8") as file:
            summary = json.load(file)

        record = {
            column: summary.get(column, "")
            for column in columns
        }

        records.append(record)

    # Export history as an Excel-compatible CSV
    with output_path.open(
        "w", newline="", encoding="utf-8-sig"
    ) as file:
        writer = csv.DictWriter(
            file,
            fieldnames=columns
        )

        writer.writeheader()
        writer.writerows(records)

    print(f"Processing history updated: {output_path}")




# Command-line arguments
parser = argparse.ArgumentParser(
    description="Retail Data Automation Pipeline"
)

parser.add_argument(
    "filename",
    help="CSV file located in data/incoming"
)
parser.add_argument("--incoming-dir", default="data/incoming",
                    help="Directory containing the input CSV")
parser.add_argument("--log-dir", default="data/logs",
                    help="Directory for pipeline diagnostic logs")
parser.add_argument("--reference-dir", default="data/raw",
                    help="Directory containing project products.csv and stores.csv")

parser.add_argument(
    "--db-path",
    default="data/database/sales.db",
    help="Target SQLite database"
)

parser.add_argument(
    "--output-dir",
    default="data/processed",
    help="Directory for analytics reports"
)

parser.add_argument(
    "--quarantine-dir",
    default=None,
    help="Directory for rejected and conflicting records"
)


args = parser.parse_args()
report_dir = resolve_project_path(args.output_dir)


if args.quarantine_dir:
    quarantine_dir = resolve_project_path(
        args.quarantine_dir
    )
elif report_dir == resolve_project_path(PROCESSED_DIR):
    quarantine_dir = resolve_project_path(QUARANTINE_DIR)
else:
    quarantine_dir = report_dir / "quarantine"


filename = args.filename



# Generate a unique identifier for this run
run_id = (
    datetime.now().strftime("%Y%m%d_%H%M%S")
    + "_"
    + uuid4().hex[:8]
)

started_at = datetime.now().astimezone().isoformat(
    timespec="seconds"
)

# Intermediate summaries generated by pipeline steps
processed_dir = BASE_DIR / "data" / "processed"
stem = Path(filename).stem


validation_path = (
    report_dir / f"{stem}_validation_summary.json"
)

load_path = (
    report_dir / f"{stem}_load_summary.json"
)


# Remove outdated intermediate summaries before this run
for path in (validation_path, load_path):
    path.unlink(missing_ok=True)


if Path(filename).name != filename or not filename.lower().endswith(".csv"):
    raise SystemExit("Please provide a CSV filename only.")


steps = [
    ("Validate & Process", "process_incoming.py"),
    ("Incremental Load", "load_sales.py"),
    ("Generate Reports", "generate_reports.py"),
]

print("\n=== RETAIL DATA AUTOMATION ===", flush=True)

for step_name, script in steps:
    print(f"\n[START] {step_name}", flush=True)

    
    
    
    command = worker_command(SRC_DIR / script)

    if script == "process_incoming.py":
        command.extend([
            filename,
            "--reference-dir", str(resolve_project_path(args.reference_dir)),
            "--incoming-dir", str(resolve_project_path(args.incoming_dir)),
            "--output-dir", str(report_dir),
            "--quarantine-dir", str(quarantine_dir)
        ])

    elif script == "load_sales.py":
        command.extend([
            filename,
            "--db-path", args.db_path,
            "--output-dir", str(report_dir),
            "--quarantine-dir", str(quarantine_dir)
        ])

    elif script == "generate_reports.py":
        command.extend([
            "--reference-dir", str(resolve_project_path(args.reference_dir)),
            "--db-path", args.db_path,
            "--output-dir", str(report_dir)
        ])





    
    result = subprocess.run(
        command,
        cwd=Path(sys.executable).parent,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env={**os.environ, "PYTHONIOENCODING": "utf-8"},
        creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0,
    )

    # Display normal script output
    if result.stdout:
        print(result.stdout, end="", flush=True)

    # Handle a failed step
    if result.returncode != 0:
        log_dir = resolve_project_path(args.log_dir)
        log_dir.mkdir(parents=True, exist_ok=True)

        log_path = log_dir / "last_error.log"

        log_path.write_text(
            f"Step: {step_name}\n"
            f"Input file: {filename}\n\n"
            f"STDOUT:\n{result.stdout}\n\n"
            f"STDERR:\n{result.stderr}",
            encoding="utf-8"
        )

        error_lines = result.stderr.strip().splitlines()

        reason = (
            error_lines[-1]
            if error_lines
            else "Unknown processing error"
        )

        print(f"\n[FAILED] {step_name}")
        print(f"Reason: {reason}")
        print(f"Diagnostic log: {log_path}")
        
        # Save a summary for this failed run
        failure_summary = {
            "run_id": run_id,
            "source_file": filename,
            "started_at": started_at,
            "completed_at": datetime.now().astimezone().isoformat(
                timespec="seconds"
            ),
            "status": "FAILED",
            "failed_step": step_name,
            "error": reason
        }

        run_dir = report_dir / "run_summaries"
        run_dir.mkdir(parents=True, exist_ok=True)

        failure_path = run_dir / f"{run_id}.json"

        failure_path.write_text(
            json.dumps(
                failure_summary,
                indent=2,
                ensure_ascii=False
            ),
            encoding="utf-8"
        )

        print(f"Failure summary saved: {failure_path}")
        export_processing_history(report_dir)


        raise SystemExit(result.returncode)

    # Show warnings from successful scripts too
    if result.stderr:
        print(result.stderr, end="", file=sys.stderr)


    print(f"[SUCCESS] {step_name}", flush=True)

print("\n=== PIPELINE COMPLETED SUCCESSFULLY ===")


# Read summaries only after all pipeline steps succeed
validation = json.loads(
    validation_path.read_text(encoding="utf-8")
)

loading = json.loads(
    load_path.read_text(encoding="utf-8")
)

# Check that the summaries belong to the correct input
if (
    validation["source_file"] != filename
    or loading["source_file"] != filename
):
    raise RuntimeError("Summary source file mismatch")

# Verify record accounting
if validation["total_records"] != (
    validation["validation_accepted"]
    + validation["validation_rejected"]
):
    raise RuntimeError("Validation record counts do not match")

if validation["validation_accepted"] != (
    loading["new_records"]
    + loading["already_present"]
):
    raise RuntimeError("Loading record counts do not match")

# Build a unified processing summary
summary = {
    "run_id": run_id,
    "source_file": filename,
    "started_at": started_at,
    "completed_at": datetime.now().astimezone().isoformat(
        timespec="seconds"
    ),
    "status": "SUCCESS",
    "total_records": validation["total_records"],
    "validation_accepted": validation["validation_accepted"],
    "validation_rejected": validation["validation_rejected"],
    "new_records": loading["new_records"],
    "already_present": loading["already_present"],
    "total_database_records": loading["total_database_records"]
}

# Preserve a separate summary for each successful run
summary_dir = report_dir / "run_summaries"
summary_dir.mkdir(parents=True, exist_ok=True)

summary_path = summary_dir / f"{run_id}.json"

summary_path.write_text(
    json.dumps(summary, indent=2, ensure_ascii=False),
    encoding="utf-8"
)

print("\n=== PROCESSING SUMMARY ===")
print(f"Run ID: {run_id}")
print(f"Input file: {filename}")
print(f"Status: {summary['status']}")
print(f"Validation rejected: {summary['validation_rejected']}")
print(f"New records: {summary['new_records']}")
print(f"Already present: {summary['already_present']}")
print(f"Summary saved: {summary_path}")
export_processing_history(report_dir)

